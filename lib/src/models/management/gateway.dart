import 'configuration.dart';
import 'json_reader.dart';

List<Map<String, dynamic>> _readMaps(Map<String, dynamic> json, String key) =>
    readList(json, key).whereType<Map<Object?, Object?>>().map(readMap).toList(growable: false);

/// A gateway: a separate deployment that serves a version of this server's configuration.
class Gateway {
  final String id;
  final String name;
  final String baseUrl;
  final String? caCertificate;
  final bool isDefault;
  final String? createdAt;
  final String? updatedAt;

  const Gateway({
    required this.id,
    required this.name,
    required this.baseUrl,
    this.caCertificate,
    this.isDefault = false,
    this.createdAt,
    this.updatedAt,
  });

  factory Gateway.fromJson(Map<String, dynamic> json) => Gateway(
        id: readString(json, 'id'),
        name: readString(json, 'name'),
        baseUrl: readString(json, 'baseUrl'),
        caCertificate: readOptionalString(json, 'caCertificate'),
        isDefault: readOptionalBool(json, 'isDefault') ?? false,
        createdAt: readOptionalString(json, 'createdAt'),
        updatedAt: readOptionalString(json, 'updatedAt'),
      );
}

/// A newly registered gateway, with the [key] it presents. This is the only time the key can be
/// read.
class GatewayRegistration {
  final Gateway gateway;
  final String? key;

  const GatewayRegistration({required this.gateway, this.key});

  factory GatewayRegistration.fromJson(Map<String, dynamic> json) =>
      GatewayRegistration(gateway: Gateway.fromJson(json), key: readOptionalString(json, 'key'));
}

/// Payload for registering a gateway. A [key] left out is generated by the server. [toString]
/// never includes the key.
class RegisterGatewayRequest {
  final String name;
  final String baseUrl;
  final String? key;
  final String? caCertificate;
  final bool? isDefault;

  const RegisterGatewayRequest({required this.name, required this.baseUrl, this.key, this.caCertificate, this.isDefault});

  Map<String, dynamic> toJson() => {
        'name': name,
        'baseUrl': baseUrl,
        if (key != null) 'key': key,
        if (caCertificate != null) 'caCertificate': caCertificate,
        if (isDefault != null) 'isDefault': isDefault,
      };

  @override
  String toString() => 'RegisterGatewayRequest(name: $name, baseUrl: $baseUrl)';
}

/// Payload for updating a gateway; only the fields set change. [toString] never includes the key.
class UpdateGatewayRequest {
  final String? name;
  final String? baseUrl;
  final String? caCertificate;
  final String? key;

  const UpdateGatewayRequest({this.name, this.baseUrl, this.caCertificate, this.key});

  Map<String, dynamic> toJson() => {
        if (name != null) 'name': name,
        if (baseUrl != null) 'baseUrl': baseUrl,
        if (caCertificate != null) 'caCertificate': caCertificate,
        if (key != null) 'key': key,
      };

  @override
  String toString() => 'UpdateGatewayRequest(name: $name, baseUrl: $baseUrl)';
}

/// Payload for applying a configuration version to a gateway.
class ApplyGatewayConfigurationRequest {
  /// The version to apply; the current one when omitted.
  final String? version;
  final bool? dryRun;

  /// Whether to go ahead when the version removes resources from the gateway.
  final bool? confirmRemovals;

  /// Apply only these change keys.
  final List<String>? selection;

  /// Leave out these change keys.
  final List<String>? skip;

  const ApplyGatewayConfigurationRequest({this.version, this.dryRun, this.confirmRemovals, this.selection, this.skip});

  Map<String, dynamic> toJson() => {
        if (version != null) 'version': version,
        if (dryRun != null) 'dryRun': dryRun,
        if (confirmRemovals != null) 'confirmRemovals': confirmRemovals,
        if (selection != null) 'selection': selection,
        if (skip != null) 'skip': skip,
      };
}

/// Payload for putting a gateway back on the version it held before the last apply.
class RevertGatewayConfigurationRequest {
  final bool? confirmRemovals;
  final bool? dryRun;

  const RevertGatewayConfigurationRequest({this.confirmRemovals, this.dryRun});

  Map<String, dynamic> toJson() => {
        if (confirmRemovals != null) 'confirmRemovals': confirmRemovals,
        if (dryRun != null) 'dryRun': dryRun,
      };
}

/// One resource's change between two configuration versions.
class GatewayConfigurationChange {
  final String? key;
  final bool? excluded;
  final bool? skipped;
  final String? resourceType;
  final String? id;
  final String? name;

  /// `added`, `updated`, `deleted` or `unchanged`.
  final String? change;

  /// The changed lines, each with a `kind` (` `, `+` or `-`) and its `text`.
  final List<Map<String, dynamic>> lines;

  const GatewayConfigurationChange({
    this.key,
    this.excluded,
    this.skipped,
    this.resourceType,
    this.id,
    this.name,
    this.change,
    this.lines = const [],
  });

  factory GatewayConfigurationChange.fromJson(Map<String, dynamic> json) => GatewayConfigurationChange(
        key: readOptionalString(json, 'key'),
        excluded: readOptionalBool(json, 'excluded'),
        skipped: readOptionalBool(json, 'skipped'),
        resourceType: readOptionalString(json, 'resourceType'),
        id: readOptionalString(json, 'id'),
        name: readOptionalString(json, 'name'),
        change: readOptionalString(json, 'change'),
        lines: _readMaps(json, 'lines'),
      );
}

/// The difference between what a gateway holds and a configuration version.
class GatewayConfigurationDiff {
  final String? fromVersion;
  final String? toVersion;

  /// The number of `added`, `updated`, `deleted` and `unchanged` resources.
  final Map<String, int> summary;
  final List<GatewayConfigurationChange> changes;

  /// Secrets referenced where a variable is expected, or the other way round.
  final List<ConfigurationValueReference> misplacedSecrets;

  const GatewayConfigurationDiff({
    this.fromVersion,
    this.toVersion,
    this.summary = const {},
    this.changes = const [],
    this.misplacedSecrets = const [],
  });

  factory GatewayConfigurationDiff.fromJson(Map<String, dynamic> json) => GatewayConfigurationDiff(
        fromVersion: readOptionalString(json, 'fromVersion'),
        toVersion: readOptionalString(json, 'toVersion'),
        summary: {
          for (final entry in readMap(json['summary']).entries)
            if (entry.value is num) entry.key: (entry.value as num).toInt(),
        },
        changes: readList(json, 'changes')
            .map((item) => GatewayConfigurationChange.fromJson(readMap(item)))
            .toList(growable: false),
        misplacedSecrets: ConfigurationValueReference.listFromJson(json, 'misplacedSecrets'),
      );
}

/// Variable and secret names, and the references to them, reported by an apply.
class GatewayValueReport {
  final List<String> variables;
  final List<String> secrets;
  final List<ConfigurationValueReference> references;

  const GatewayValueReport({this.variables = const [], this.secrets = const [], this.references = const []});

  factory GatewayValueReport.fromJson(Map<String, dynamic> json) => GatewayValueReport(
        variables: readStringList(json, 'variables'),
        secrets: readStringList(json, 'secrets'),
        references: ConfigurationValueReference.listFromJson(json, 'references'),
      );
}

/// The result of applying or reverting a gateway's configuration.
class GatewayApplyResult {
  final String? gatewayId;
  final bool? dryRun;
  final GatewayConfigurationDiff? diff;

  /// The gateway's import result, as the gateway reported it.
  final Map<String, dynamic>? import;

  /// Whether the applied version was recorded as the gateway's.
  final bool? recorded;

  /// Values the version references that the gateway does not have.
  final GatewayValueReport? missing;

  /// Values whose content changed since the gateway last received them.
  final GatewayValueReport? changed;

  /// Whether the apply was queued (HTTP 202) to run when the gateway is free.
  final bool? queued;
  final String? queuedVersion;

  const GatewayApplyResult({
    this.gatewayId,
    this.dryRun,
    this.diff,
    this.import,
    this.recorded,
    this.missing,
    this.changed,
    this.queued,
    this.queuedVersion,
  });

  factory GatewayApplyResult.fromJson(Map<String, dynamic> json) => GatewayApplyResult(
        gatewayId: readOptionalString(json, 'gatewayId'),
        dryRun: readOptionalBool(json, 'dryRun'),
        diff: json['diff'] is Map ? GatewayConfigurationDiff.fromJson(readMap(json['diff'])) : null,
        import: readOptionalMap(json['import']),
        recorded: readOptionalBool(json, 'recorded'),
        missing: json['missing'] is Map ? GatewayValueReport.fromJson(readMap(json['missing'])) : null,
        changed: json['changed'] is Map ? GatewayValueReport.fromJson(readMap(json['changed'])) : null,
        queued: readOptionalBool(json, 'queued'),
        queuedVersion: readOptionalString(json, 'queuedVersion'),
      );
}

/// The configuration a gateway holds, resource by resource.
class GatewayAppliedConfiguration {
  final String gatewayId;
  final String? version;
  final String? appliedAt;

  /// Each with its `resourceType`, `id`, `resource` and optional `parts`.
  final List<Map<String, dynamic>> resources;

  /// Each with its `resourceType`, optional `id`, `code` and `reason`.
  final List<Map<String, dynamic>> skipped;

  const GatewayAppliedConfiguration({
    required this.gatewayId,
    this.version,
    this.appliedAt,
    this.resources = const [],
    this.skipped = const [],
  });

  factory GatewayAppliedConfiguration.fromJson(Map<String, dynamic> json) => GatewayAppliedConfiguration(
        gatewayId: readString(json, 'gatewayId'),
        version: readOptionalString(json, 'version'),
        appliedAt: readOptionalString(json, 'appliedAt'),
        resources: _readMaps(json, 'resources'),
        skipped: _readMaps(json, 'skipped'),
      );
}

/// The configuration version a gateway holds, and the one before it.
class GatewayAppliedVersion {
  final String? gatewayId;
  final String? appliedVersion;
  final String? previousVersion;
  final String? appliedAt;
  final ConfigurationActor? appliedBy;

  const GatewayAppliedVersion({
    this.gatewayId,
    this.appliedVersion,
    this.previousVersion,
    this.appliedAt,
    this.appliedBy,
  });

  factory GatewayAppliedVersion.fromJson(Map<String, dynamic> json) => GatewayAppliedVersion(
        gatewayId: readOptionalString(json, 'gatewayId'),
        appliedVersion: readOptionalString(json, 'appliedVersion'),
        previousVersion: readOptionalString(json, 'previousVersion'),
        appliedAt: readOptionalString(json, 'appliedAt'),
        appliedBy: ConfigurationActor.tryFromJson(json['appliedBy']),
      );
}
